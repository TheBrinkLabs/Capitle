class CountryFlagEntry {
  final String name;
  final String isoCode; // ISO 3166-1 alpha-2

  const CountryFlagEntry(this.name, this.isoCode);

  /// Flag emoji derived mechanically from the ISO code via the Unicode
  /// regional-indicator-symbol trick — no need to hand-curate emoji
  /// alongside every name, and no risk of a copy-paste mismatch.
  String get flagEmoji => isoToFlagEmoji(isoCode);
}

String isoToFlagEmoji(String iso) {
  return iso.toUpperCase().codeUnits.map((c) => String.fromCharCode(c + 127397)).join();
}

